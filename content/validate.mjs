import {rarityFor} from '../web/rarity.js';
import {strict as assert} from 'node:assert';
import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {normalizeAnswer} from './match.mjs';
import {buildSchedule} from './schedule.mjs';

const dated = '2026-11-12';
const tierValues=[10,15,30,60,85,100];
const counter = (map,key) => map.set(key,(map.get(key)??0)+1);
export function validateRelease(release) {
  const ids=new Set(), concepts=new Map(), families=new Map(), tierNames=new Map(), tiers=new Map(), prompts=new Map();
  const sources=new Map(release.sources.map(s=>[s.id,s]));
  assert.equal(sources.size,release.sources.length,'Duplicate source ID');
  for (const s of sources.values()) assert.ok(s.license && s.version && new URL(s.url).protocol==='https:','Missing source manifest');
  for (const tier of release.tiers) tierNames.set(tier.name,tier.points);
  assert.deepEqual([...tierNames.values()].sort((a,b)=>a-b),tierValues,'Unapproved tier ladder');
  let pairs=0, aliases=0, tops=0, educational=0;
  for (const p of release.prompts) {
    assert.ok(p.text && p.scope && p.topic,'Missing scope');
    assert.ok(!ids.has(p.id),'Duplicate prompt ID: '+p.id);
    assert.ok(['daily','open'].includes(p.pool),'Invalid pool: '+p.id);
    ids.add(p.id);prompts.set(p.id,p);
    const family=families.get(p.topic)??{prompts:0,mappings:0,open:0};families.set(p.topic,family);
    family.prompts++;family.mappings+=p.answers.length;if(p.pool==='open')family.open++;
    const index=new Map(),seen=new Set(), ambiguous=new Set(p.ambiguous.map(normalizeAnswer)),excluded=new Set(p.exclusions.map(normalizeAnswer));
    for(const key of ambiguous)assert.ok(!excluded.has(key),'Contradictory rejection: '+key);
    for(const a of p.answers){
      const context=p.id+' / '+a.term;
      assert.ok(!seen.has(a.id),'Duplicate mapping: '+context);seen.add(a.id);
      if(concepts.has(a.id))assert.equal(concepts.get(a.id),a.term,'Inconsistent canonical term: '+a.id);
      concepts.set(a.id,a.term);
      assert.equal(tierNames.get(a.tier),a.points,context);
      assert.ok(a.reason?.length>=15 && a.fact?.length>=12 && a.evidence?.length>=20,context);
      assert.ok(sources.has(a.source.id) && a.source.label && new URL(a.source.url).protocol==='https:',context);
      assert.equal(new URL(a.source.url).username,'',context);
      if(a.points===100){tops++;assert.ok(!a.fact.includes('medical subject index'),context+' needs an authored top fact');}
      if(!a.fact.includes('medical subject index'))educational++;
      for(const candidate of [a.term,...a.aliases]){
        const key=normalizeAnswer(candidate);
        assert.ok(key.length>0 && key.length<=96,'Invalid alias: '+context);
        assert.ok(!excluded.has(key),'Excluded alias: '+context);
        if(index.has(key) && !ambiguous.has(key))throw new Error('Duplicate normalized alias '+p.id+' / '+key);
        index.set(key,a.id);
      }
      aliases+=a.aliases.length; pairs++;counter(tiers,a.tier);
    }
    assert.ok(p.answers.some(a=>a.points===100),'Unattainable 100 ceiling: '+p.id);
  }
  assert.ok(ids.size>=84 && pairs>=1000 && families.size>=8,'Insufficient launch inventory');
  const pool=release.prompts.filter(p=>p.pool==='open');
  assert.ok(pool.filter(p=>p.answers.length>=12).length>=12,'Insufficient open Relay pool');
  assert.equal(prompts.get('instruments').pool,'open','Demo overlap');
  const maxDays=366;
  const first=buildSchedule(dated,maxDays,release),prev=new Map(),selected=new Set();
  let minGap=Infinity,minFamilies=7;
  for(let day=0;day<first.length;day++){
    const issue=first[day];
    assert.equal(issue.prompts.length,7);assert.equal(new Set(issue.prompts).size,7,'Repeated slot');
    const topics=new Set();
    for(const id of issue.prompts){
      const p=prompts.get(id);assert.ok(p && p.pool==='daily','Reserved/open mix');
      if(prev.has(id)){const gap=day-prev.get(id);minGap=Math.min(minGap,gap);assert.ok(gap>=8,'Too-soon repeat: '+id);}
      prev.set(id,day);topics.add(p.topic);if(day<28)selected.add(id);
    }
    assert.ok(prompts.get(issue.prompts[0]).opener,'Missing introductory prompt');
    minFamilies=Math.min(minFamilies,topics.size);assert.ok(topics.size>=4,'Issue lacks topic mix');
  }
  for(const day of [0,6,7,27,90,185,365]){
    assert.deepEqual(buildSchedule(first[day].date,1,release)[0],first[day],'Refill boundary changed: '+day);
  }
  return {pairs,aliases,tops,educational,concepts:concepts.size,families,tiers,openCount:pool.length,openPairs:pool.reduce((n,p)=>n+p.answers.length,0),minGap,minFamilies,selected:selected.size,issues:first.slice(0,28)};
}

function report(r,s) {
  const lines=['# Launch inventory','',
    'Content release `'+r.id+'` · scoring release `'+r.scoringRelease+'`. Generated by `node content/validate.mjs --report`.','',
    r.prompts.length+' scoped prompts contain **'+s.pairs+' accepted prompt–concept pairs**, drawn from '+s.concepts+' distinct canonical identifiers. The '+s.aliases+' additional spellings do not contribute to either count. Each answer has a scoring decision, an editorial reason, a short sourced fact and mapping evidence.','',
    '| Topic | Prompts | Accepted pairs | Open prompts |','| --- | ---: | ---: | ---: |'];
  for(const [key,v] of s.families)lines.push('| '+key+' | '+v.prompts+' | '+v.mappings+' | '+v.open+' |');
  lines.push('','| Editorial tier | Points | Pairs |','| --- | ---: | ---: |');
  for(const t of r.tiers)lines.push('| '+rarityFor(t.points).label+' | '+t.points+' | '+s.tiers.get(t.name)+' |');
  lines.push('','The open pool has '+s.openCount+' prompts and '+s.openPairs+' accepted mappings. These prompts are never scheduled for ranked play. The playable concept uses the surgical prompt, which stays in the open pool.','',
    'The first 28 published issues below cover '+s.selected+' distinct daily prompts. In a 366-issue simulation each issue mixes at least '+s.minFamilies+' families, and repeats are at least '+s.minGap+' issue numbers apart ('+(s.minGap-1)+' intervening issues). Every issue opens with an introductory prompt. Each daily has an attainable maximum of 700. Scheduling and time-zone rules are documented in the content README.','',
    '| Eastern date | Issue | Ordered prompt IDs (server only) |','| --- | ---: | --- |');
  for(const i of s.issues)lines.push('| '+i.date+' | '+i.number+' | '+i.prompts.join(', ')+' |');
  lines.push('','The demo bank, archive runs, tests and synthetic traffic are excluded. All tier counts are editorial assignments. Observed frequency is calculated separately from eligible completed runs.','');
  return lines.join('\n');
}

function writeReports(release, result) {
  const write = (file, value) => writeFileSync(new URL(file, import.meta.url), value);
  write('./INVENTORY.md', report(release, result));

  const picks = [
    '# Top-pick editorial ledger', '',
    'Server-only review copy for `' + release.id + '`. Every listed mapping awards 100 points under its stated scope. The source link supports the medical fact. The judgment about recall belongs to the editors.', '',
    '| Prompt | Canonical pick | Short fact | Editorial rationale | Source |',
    '| --- | --- | --- | --- | --- |'
  ];
  for (const prompt of release.prompts) {
    for (const answer of prompt.answers.filter(candidate => candidate.points === 100)) {
      picks.push('| ' + [prompt.text, answer.term, answer.fact, answer.reason,
        '[' + answer.source.label + '](' + answer.source.url + ')'].join(' | ') + ' |');
    }
  }
  write('./TOP-PICKS.md', picks.join('\n') + '\n');

  const rights = [
    '# Content source and rights manifest', '',
    'Selected names, identifiers and relationships are derived from the United States National Library of Medicine, 2026 Medical Subject Headings (MeSH). Penicillion selected the entries, assigned recall tiers and wrote its own facts. NLM does not endorse this game. NLM provides its data without warranty. The release includes English preferred terms and uses the 2026 descriptor version. [NLM terms and conditions](https://www.nlm.nih.gov/databases/download/terms_and_conditions_mesh.html)', '',
    'The other medical sources supplied factual verification, nomenclature and bibliographic links. The game does not embed their pages, illustrations, definitions or tables. A source hosted by NIH or FDA can still have third-party authors. Record the rights basis for each new source before building the release.', '',
    '| Reference | Version or access date | Material and terms |', '| --- | --- | --- |'
  ];
  for (const source of release.sources) {
    rights.push('| [' + source.label + '](' + source.url + ') | ' + source.version +
      ' | ' + source.license.replace('https://www.nlm.nih.gov/databases/download/terms_and_conditions_mesh.html. ', '') + ' |');
  }
  rights.push('', 'The bundled subset can be regenerated using the pinned source digest and extraction instructions in [Content operations](README.md). Each individual mapping stores its source ID, direct URL, membership evidence, authored fact and editorial rationale.', '');
  write('./LICENSES.md', rights.join('\n'));
}
if(process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href){
  const path=process.argv.slice(2).find(s=>!s.startsWith('--'));
  const release=JSON.parse(readFileSync(path??new URL('./release.json',import.meta.url),'utf8'));
  const result=validateRelease(release);
  if(process.argv.includes('--report'))writeReports(release,result);
  console.log(release.id+': '+release.prompts.length+' prompts, '+result.pairs+' mappings, '+result.families.size+' families; '+result.openCount+' permanently open. Schedule passes 366-issue checks.');
}
